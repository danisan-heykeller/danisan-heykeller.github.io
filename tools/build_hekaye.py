# Builds assets/hekaye.js for Hekayə avtomatı: texts from tools/hekaye/*.md + metro graph for ride time.
#   python3 tools/build_hekaye.py
# Text file format: front matter (id, author_az/ru, title_az/ru, test, source) then [az] ... [ru] ... blocks.
import json, os, re, glob

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
WPM = 170  # comfortable phone reading speed, words per minute

def parse(path):
    raw = open(path, encoding="utf-8").read()
    fm, body = raw.split("---", 2)[1:]
    meta = {}
    for line in fm.strip().splitlines():
        k, v = line.split(":", 1); meta[k.strip()] = v.strip()
    parts = re.split(r"^\[(az|ru)\]\s*$", body.strip(), flags=re.M)
    txt = {parts[i]: parts[i + 1].strip() for i in range(1, len(parts), 2)}
    out = {"id": meta["id"], "test": meta.get("test") == "true", "source": meta.get("source", ""),
           "author": {"az": meta["author_az"], "ru": meta["author_ru"]},
           "title": {"az": meta["title_az"], "ru": meta["title_ru"]}, "text": {}, "min": {}}
    for k, v in txt.items():
        paras = [p.strip() for p in re.split(r"\n\s*\n", v) if p.strip()]
        words = sum(len(p.split()) for p in paras)
        out["text"][k] = paras
        out["min"][k] = max(1, round(words / WPM))
    return out

texts = [parse(p) for p in sorted(glob.glob(os.path.join(ROOT, "tools/hekaye/*.md")))]

# Metro graph: travel between neighbours ~2 min, transfer ~4 min (estimates, shown to users as approximate)
HOP, XFER = 2, 4
red = ["icherisheher", "sahil", "28may", "genclik", "nerimanov", "ulduz", "koroglu", "qarayev", "neftchiler", "xalqlar", "ehmedli", "aslanov"]
green = ["dernegul", "azadliq", "nesimi", "ecemi", "20yanvar", "inshaatchilar", "elmler", "nizami", "cabbarli", "xetai"]
purple = ["xocesen", "avtovagzal", "ecemi2", "8noyabr"]
edges = []
for line in (red, green, purple):
    edges += [[a, b, HOP] for a, b in zip(line, line[1:])]
edges += [["nerimanov", "bakmil", HOP], ["28may", "cabbarli", XFER], ["ecemi", "ecemi2", XFER]]

with open(os.path.join(ROOT, "assets/hekaye.js"), "w", encoding="utf-8") as f:
    f.write("/* Hekayə avtomatı - generated by tools/build_hekaye.py; edit texts in tools/hekaye/. */\n")
    f.write("window.DH_HEKAYE = " + json.dumps({"wpm": WPM, "edges": edges, "texts": texts}, ensure_ascii=False, indent=1) + ";\n")
for t in texts:
    print(t["id"], t["min"])
